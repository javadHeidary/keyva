import 'dart:typed_data';

import 'package:keyva/feature/type/image/service/image_capture_service.dart';

class FakeImageCaptureService implements ImageCaptureService {
  FakeImageCaptureService({ImageCaptureOutcome? outcome})
    : outcome = outcome ??
          ImageCaptureSuccess(
            ImageCaptureData(
              bytes: oneByOnePng,
              thumbnailBytes: oneByOnePng,
              mimeType: 'image/png',
              width: 1,
              height: 1,
            ),
          );

  ImageCaptureOutcome outcome;
  ImageCaptureSource? lastSource;
  int pickCount = 0;

  @override
  Future<ImageCaptureOutcome> pick(ImageCaptureSource source) async {
    pickCount++;
    lastSource = source;
    return outcome;
  }
}

final Uint8List oneByOnePng = Uint8List.fromList(const [
  0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A, 0x00, 0x00, 0x00, 0x0D,
